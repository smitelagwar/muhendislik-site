import { expect, test, type Page } from "@playwright/test";
import fs from "node:fs/promises";
import { smallSlab } from "../hsyncad-structural/report-fixtures";

async function openSettings(page: Page) {
  await page.getByRole("textbox", { name: "Komut ara", exact: true }).fill("Analiz Ayarları Raporu");
  await page.getByRole("button", { name: /^Analiz Ayarları Raporu/ }).first().click();
  await expect(page.getByTestId("project-analysis-settings")).toBeVisible();
}
test("legacy -> blank settings -> validation -> units -> save/download/reopen -> other project isolation", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  const original = { ...smallSlab(), preservedExtension: { label: "eski özel veri", value: 123 } };
  await page.goto("/kategori/araclar/hsyncad");
  await expect(page.getByTestId("hsyncad-workbench")).toHaveAttribute("data-ready", "true");
  await page.getByTestId("hsyncad-import").setInputFiles({ name: "legacy.hsyncad", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(original)) });
  await expect.poll(() => page.evaluate(() => !!JSON.parse(localStorage.getItem("hsyncad.model.v1")!).structural)).toBe(true);
  await openSettings(page);
  await expect(page.getByTestId("setting-r")).toHaveValue("");
  await expect(page.getByTestId("setting-concreteGrade")).toHaveValue("");
  await page.getByTestId("setting-qt").fill("NaN");
  await page.getByTestId("save-project-settings").click();
  await expect(page.getByTestId("setting-qt")).toBeFocused();
  await page.getByTestId("setting-qt").fill("");
  await page.getByRole("combobox", { name: "Basınç giriş birimi", exact: true }).selectOption("tf/m2");
  await page.getByTestId("setting-qt").fill("55");
  await page.getByRole("combobox", { name: "Basınç giriş birimi", exact: true }).selectOption("kPa");
  expect(Number(await page.getByTestId("setting-qt").inputValue())).toBeCloseTo(55 * 9.80665, 8);
  await page.getByRole("combobox", { name: "Basınç giriş birimi", exact: true }).selectOption("tf/m2");
  await page.getByRole("combobox", { name: "Kuvvet/hacim giriş birimi", exact: true }).selectOption("tf/m3");
  await page.getByTestId("setting-subgrade").fill("3080");
  await page.getByTestId("setting-dryUnitWeight").fill("2,1");
  await page.getByTestId("setting-saturatedUnitWeight").fill("2,5");
  await page.getByTestId("setting-r").fill("8");
  await page.getByTestId("setting-concreteGrade").selectOption("C25");
  await page.getByTestId("setting-soilClass").selectOption("ZD");
  await page.getByTestId("setting-soilBehavior").selectOption("cohesionless");
  await page.getByTestId("save-project-settings").click();
  await expect(page.getByTestId("project-analysis-settings")).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("hsyncad.model.v1")!).structural.revision)).toBe(1);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("hsyncad.model.v1")!));
  expect(saved.structural.settings.qt.value).toBeCloseTo(55 * 9.80665, 8);
  expect(saved.structural.settings.subgrade.value).toBeCloseTo(3080 * 9.80665, 8);
  expect(saved.structural.settings.allowablePressure.value).toBe(null);
  expect(saved.structural.coefficients.r.used).toBe(null);
  expect(saved.structural.legacyArchive).toEqual(original);
  const downloaded = page.waitForEvent("download", { timeout: 8000 });
  await page.getByRole("button", { name: "Çalışmayı kaydet · .hsyncad", exact: true }).click();
  const output = info.outputPath("P03-saved.hsyncad"); await (await downloaded).saveAs(output);
  const bytes = await fs.readFile(output);
  expect(JSON.parse(bytes.toString())).toEqual(saved);
  await page.getByTestId("hsyncad-import").setInputFiles({ name: "reopen.hsyncad", mimeType: "application/json", buffer: bytes });
  await openSettings(page);
  expect(Number(await page.getByTestId("setting-qt").inputValue())).toBeCloseTo(55 * 9.80665, 8);
  await expect(page.getByTestId("setting-soilBehavior")).toHaveValue("cohesionless");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: info.outputPath("settings-mobile.png") });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Ayarları kapat", exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.getByTestId("hsyncad-import").setInputFiles({ name: "other.hsyncad", mimeType: "application/json", buffer: Buffer.from(JSON.stringify({ ...smallSlab(), name: "Başka proje" })) });
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("hsyncad.model.v1")!).name)).toBe("Başka proje");
  await openSettings(page);
  await expect(page.getByTestId("setting-qt")).toHaveValue("");
  await expect(page.getByTestId("setting-concreteGrade")).toHaveValue("");
  await page.screenshot({ path: info.outputPath("settings-desktop.png") });
  expect(errors).toEqual([]);
});
