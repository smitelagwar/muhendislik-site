let updatedCount = 0;
for (const relPath of targetFiles) {
  const fullPath = path.resolve(process.cwd(), relPath);
  if (!fs.existsSync(fullPath)) {
    console.warn("File not found:", relPath);
    continue;
  }

  let content = fs.readFileSync(fullPath, "utf-8");
  let modified = content;

  for (const [regex, replacement] of DICT) {
    modified = modified.replace(regex, replacement);
  }

  // Restore any accidentally modified code identifier keys
  modified = modified
    .replace(/BRANCH_SOURCE_LEDGER\["ince-işler"\]/g, 'BRANCH_SOURCE_LEDGER["ince-isler"]')
    .replace(/BRANCH_SOURCE_LEDGER\["tesisat-işleri"\]/g, 'BRANCH_SOURCE_LEDGER["tesisat-isleri"]')
    .replace(/BRANCH_SOURCE_LEDGER\["peyzaj-teslim"\]/g, 'BRANCH_SOURCE_LEDGER["peyzaj-teslim"]');

  if (modified !== content) {
    fs.writeFileSync(fullPath, modified, "utf-8");
    updatedCount++;
    console.log(`Enriched and corrected Turkish in Stage 2 file: ${relPath}`);
  }
}

console.log(`Updated ${updatedCount} Stage 2 files.`);
