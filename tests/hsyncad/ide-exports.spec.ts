import { expect, test } from "@playwright/test";
import fs from "node:fs/promises";
import { existsSync } from "node:fs";

const fixture = "C:/Users/hsyn/Desktop/hsyncad/incelemeler/idecad-rea/native-2026-11-04/hsyncad-paneller-test.ide11trial";

test("native IDE opens, edits, undoes, deletes and saves a reopened editable workspace", async ({ page }, testInfo) => {
  test.skip(!existsSync(fixture), "Requires actual native fixture");
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/kategori/araclar/hsyncad");
  await expect(page.getByTestId("hsyncad-workbench")).toHaveAttribute("data-ready", "true");
  await page.getByTestId("hsyncad-import").setInputFiles(fixture);
  await expect(page.getByTestId("hsyncad-ide-import-report")).toContainText("11 eleman", { timeout: 30_000 });
  const column = await page.evaluate(() => JSON.parse(localStorage.getItem("hsyncad.model.v1")!).elements.find((e: { type: string }) => e.type === "column"));
  const plan = page.getByTestId("hsyncad-plan"), box = (await plan.boundingBox())!;
  const camera = JSON.parse((await plan.getAttribute("data-camera"))!);
  await page.mouse.click(box.x + box.width / 2 + (column.position.x - camera.x) * camera.scale, box.y + box.height / 2 - (column.position.y - camera.y) * camera.scale);
  await expect(page.getByTestId("hsyncad-properties")).toBeVisible();
  await page.getByTestId("property-width").fill("0.65");
  await page.getByRole("button", { name: "Değişiklikleri uygula", exact: true }).click();
  const width = () => page.evaluate(id => JSON.parse(localStorage.getItem("hsyncad.model.v1")!).elements.find((e: { id: string }) => e.id === id)?.width, column.id);
  await expect.poll(width).toBe(.65);
  await page.getByRole("button", { name: "Geri al", exact: true }).click();
  await expect.poll(width).toBe(column.width);
  await page.getByRole("button", { name: "Yinele", exact: true }).click();
  await expect.poll(width).toBe(.65);
  const downloaded = page.waitForEvent("download", { timeout: 8000 });
  await page.getByRole("button", { name: "Çalışmayı kaydet · .hsyncad", exact: true }).click();
  const download = await downloaded, savedPath = testInfo.outputPath("edited.hsyncad");
  expect(download.suggestedFilename()).toMatch(/\.hsyncad$/);
  await download.saveAs(savedPath);
  const saved = JSON.parse(await fs.readFile(savedPath, "utf8"));
  expect(saved.elements.find((e: { id: string }) => e.id === column.id).width).toBe(.65);
  await page.getByTestId("hsyncad-workbench").focus(); await page.keyboard.press("Delete");
  await expect.poll(async () => page.evaluate(() => JSON.parse(localStorage.getItem("hsyncad.model.v1")!).elements.length)).toBe(10);
  await page.getByTestId("hsyncad-import").setInputFiles(savedPath);
  await expect.poll(width).toBe(.65);
  await page.reload();
  await expect(page.getByTestId("hsyncad-ide-import-report")).toBeVisible();
  await expect.poll(width).toBe(.65);
  const before = await page.evaluate(() => localStorage.getItem("hsyncad.model.v1"));
  await page.getByTestId("hsyncad-import").setInputFiles({ name: "broken.ide11", mimeType: "application/octet-stream", buffer: Buffer.from("invalid") });
  await expect(page.getByTestId("hsyncad-message")).toContainText("Dosya açılamadı");
  expect(await page.evaluate(() => localStorage.getItem("hsyncad.model.v1"))).toBe(before);
  expect(errors).toEqual([]);
});
