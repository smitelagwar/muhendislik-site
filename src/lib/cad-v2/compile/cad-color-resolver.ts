/**
 * ACI (AutoCAD Color Index) numarasını RGB [0..1] üçlüsüne çevirir
 */
export function aciToRgb(aci: number): [number, number, number] {
  if (!Number.isFinite(aci)) return [1, 1, 1];
  const idx = Math.abs(Math.round(aci));
  if (idx >= 0 && idx < ACI_COLOR_TABLE.length) {
    return ACI_COLOR_TABLE[idx];
  }
  return [1, 1, 1]; // Bilinmeyen renk için varsayılan beyaz
}

/**
 * CadColor tanımını RGB [0..1] üçlüsüne çevirir
 */
export function cadColorToRgb(color: CadColor | undefined): [number, number, number] | null {
  if (!color) return null;

  if (color.method === "rgb" && color.rgb && color.rgb.length === 3) {
    return [color.rgb[0] / 255, color.rgb[1] / 255, color.rgb[2] / 255];
  }

  if (color.method === "aci" && typeof color.aci === "number") {
    return aciToRgb(color.aci);
  }

  return null;
}

/**
 * Bir varlık ve katmanlar kümesinden nihai çizim RGB rengini çözümler:
 * 1. Varlıkta açık RGB veya ACI varsa o kullanılır.
 * 2. Varlık ByLayer ise katman rengi çözümlenir.
 * 3. Katmanda renk yoksa standart ACI 7 (Beyaz) döner.
 */
export function resolveEntityColor(
  ent: Pick<CadEntity, "color" | "layer">,
  layers: Record<string, CadLayer>
): [number, number, number] {
  // 1. Doğrudan varlık rengi (ByLayer veya ByBlock değilse)
  if (ent.color && ent.color.method !== "byLayer" && ent.color.method !== "byBlock") {
    const directRgb = cadColorToRgb(ent.color);
    if (directRgb) return directRgb;
  }

  // 2. Katman rengi
  const layerName = ent.layer || "0";
  const layer = layers[layerName];
  if (layer && layer.color) {
    const layerRgb = cadColorToRgb(layer.color);
    if (layerRgb) return layerRgb;
  }

  // 3. Varsayılan CAD rengi (Beyaz/Açık Gri)
  return [0.9, 0.9, 0.9];
}
