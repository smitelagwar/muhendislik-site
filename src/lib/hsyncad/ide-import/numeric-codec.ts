function f(value: number): number {
  return (((S[value >>> 24] + S[256 + ((value >>> 16) & 255)]) ^ S[512 + ((value >>> 8) & 255)]) + S[768 + (value & 255)]) >>> 0;
}

/** Decode one native 8-byte block; all integer/string reads stay untouched. */
export function decodeIdeNumericBlock(source: DataView, byteOffset: number): Uint8Array<ArrayBuffer> {
  // Native DataView validates/coerces the index and the complete 8-byte range.
  DataView.prototype.getFloat64.call(source, byteOffset, true);
  const offset = Math.trunc(Number(byteOffset)) || 0;
  let left = source.getUint32(offset, false), right = source.getUint32(offset + 4, false);
  for (let i = 17; i >= 2; i--) {
    left = (left ^ P[i]) >>> 0;
    right = (right ^ f(left)) >>> 0;
    [left, right] = [right, left];
  }
  [left, right] = [right, left];
  right = (right ^ P[1]) >>> 0; left = (left ^ P[0]) >>> 0;
  const bytes = new Uint8Array(8), decoded = new DataView(bytes.buffer);
  decoded.setUint32(0, left, false); decoded.setUint32(4, right, false);
  return bytes;
}

export function hasIdeEncodedNumbers(buffer: ArrayBuffer): boolean {
  const header = new DataView(buffer);
  return header.byteLength >= 83 && header.getUint8(78) === 1 && header.getUint32(74, true) === 211220;
}

class IdeEncodedDataView extends DataView<ArrayBuffer> {
  override getFloat64(byteOffset: number, littleEndian?: boolean): number {
    return new DataView(decodeIdeNumericBlock(this, byteOffset).buffer).getFloat64(0, littleEndian);
  }
}

/** Select by the actual carrier header, independently of its filename. */
export function createIdeDataView(buffer: ArrayBuffer): DataView {
  const raw = new DataView(buffer);
  if (raw.byteLength < 83 || raw.getUint8(78) !== 1) return raw;
  if (!hasIdeEncodedNumbers(buffer)) throw new Error("Bu IDE dosyasının sayısal kodlama sürümü henüz desteklenmiyor.");
  return new IdeEncodedDataView(buffer);
}


export function isIde11SchemaVersion(buffer: ArrayBuffer): boolean {
  const header = new DataView(buffer);
  return header.byteLength >= 83 && header.getUint32(74, true) >= 211150;
}

/** Encode one 8-byte IEEE-754 float64 block using the inverse of decodeIdeNumericBlock. */
export function encodeIdeNumericBlock(source: DataView, byteOffset = 0): Uint8Array<ArrayBuffer> {
  DataView.prototype.getFloat64.call(source, byteOffset, true);
  const offset = Math.trunc(Number(byteOffset)) || 0;
  let left = source.getUint32(offset, false), right = source.getUint32(offset + 4, false);
  for (let i = 0; i < 16; i++) {
    left = (left ^ P[i]) >>> 0;
    right = (right ^ f(left)) >>> 0;
    [left, right] = [right, left];
  }
  [left, right] = [right, left];
  right = (right ^ P[16]) >>> 0;
  left = (left ^ P[17]) >>> 0;
  const bytes = new Uint8Array(8), encoded = new DataView(bytes.buffer);
  encoded.setUint32(0, left, false);
  encoded.setUint32(4, right, false);
  return bytes;
}

export function encodeIdeFloat64(value: number): Uint8Array<ArrayBuffer> {
  const raw = new Uint8Array(8);
  new DataView(raw.buffer).setFloat64(0, value, true);
  return encodeIdeNumericBlock(new DataView(raw.buffer), 0);
}
